# Copies Sources/TrailwardenCore/Resources/rules.json into a Swift string, so the
# command line tools and the MCP server carry their rules inside the binary and
# work wherever they are copied (Homebrew, the release tarball, npm, make
# install). rules.json stays the file you edit; run this afterwards. A test
# fails when the two differ.
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
source = root / "Sources/TrailwardenCore/Resources/rules.json"
target = root / "Sources/TrailwardenCore/Rules/BuiltInRules.swift"

text = source.read_text(encoding="utf-8")
json.loads(text)  # refuse to embed a broken file
if '"####' in text:
    sys.exit("rules.json contains the raw-string delimiter; change it in embed-rules.py")

target.write_text(
    "// SPDX-License-Identifier: Apache-2.0\n"
    "// Copyright (c) 2026 Turgay Nalbant\n"
    "//\n"
    "// Generated by scripts/embed-rules.py from Resources/rules.json — edit that file\n"
    "// and run the script; do not edit this one.\n\n"
    "enum BuiltInRules {\n"
    '    static let json = ####"""\n'
    + text
    # A multi-line literal drops the line break before its closing quotes; one
    # more keeps the file's own final newline in the string.
    + "\n"
    + '"""####\n'
    "}\n",
    encoding="utf-8",
)
print(f"embedded {source.relative_to(root)} -> {target.relative_to(root)}")
